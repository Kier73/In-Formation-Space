"""GCI-005: phase-blind authenticated-observer agreement and disagreement audit.

Do not infer truth from one self-signed test-domain identity. Two distinct
validly signed host receipts that conflict must not authorize a result. This
independent verifier needs the public source Ground, but NOT the private phase.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any, Mapping

from cryptography import x509
from cryptography.hazmat.primitives import serialization

HERE=Path(__file__).resolve()
sys.path.insert(0, str(HERE.parents[1]/"gci004"))
import fabric_contract as c

gci3=c.gci3
cag=c.cag
require=gci3.require

SCHEMA="in-formation.gci005-signed-observer-disagreement/0.1"
AUDIT_SCHEMA="in-formation.gci005-blind-disagreement-audit/0.1"
WITNESS_SCHEMA="in-formation.gci005-private-witness-audit/0.1"
TASK="far-y-parity"
FEATURE="parity"
TWO=("observer-a","observer-b")
SCENARIOS=("honest-agreement","signed-false-reading")
SCOPE=[
    "Two separate E-CPU observer processes speak real loopback TCP mTLS on one GitHub-hosted runner.",
    "Both parity readings are signed with distinct ephemeral X.509 server leaf keys from one job-local CA.",
    "The second scenario deliberately makes one authorized server sign an incorrect mathematical reading.",
    "Agreement is only consistency, not proof of truth; two colluding or identical faulty observers could agree.",
    "The phase-blind coordinator and independent auditor do not consume the private phase artifact.",
    "A separate witness auditor later checks exactly which peer told the truth using the held phase.",
    "The test CA is generated by the same host job; it does not establish cross-administrator PKI.",
    "Local TLS, discovery and request latencies are measured samples; they imply no general performance bound.",
]


def strict_ns(value: Any, label: str) -> None:
    require(type(value) is int and 0 < value < 10**12,
            label+" must be a measured positive integer number of nanoseconds")


def decisions(values: Mapping[str, Any]) -> dict[str, Any]:
    """Pure phase-blind verdict: a pair of valid peers may agree or conflict."""
    require(type(values) is dict and set(values)==set(TWO) and
            all(type(values[k]) is int and values[k] in (0,1) for k in TWO),
            "paired parity readings must be distinct hosts' two strict bits")
    consistent=values[TWO[0]]==values[TWO[1]]
    return {"status":"ADMITTED_AGREEMENT" if consistent else "REFUSED_DISAGREEMENT",
            "task_id":TASK,"feature":FEATURE,
            "admitted_value":values[TWO[0]] if consistent else None,
            "returned_result":False if not consistent else True,
            "matching_receipt_count":2 if consistent else 0}


def get_binding(directory: Path) -> tuple[dict,dict,dict]:
    binding=gci3.certificate_binding(directory)
    public=cag.read(directory/"gci003-public.json")
    plan=cag.read(directory/"gci003-plan.json")
    gci3.validate_plan(plan,public,binding)
    selected=next(x for x in plan["cases"] if x["case_id"]==TASK)
    require(selected["status"]=="MEASURE" and selected["selected"]==[FEATURE],
            "signed intention does not authorize a parity measurement")
    return binding,public,plan


def verify_record(report: Mapping[str, Any], binding: Mapping[str,str],
                  public: Mapping[str,Any], plan: Mapping[str,Any]) -> dict[str,Any]:
    """Validate real report and receipt signatures WITHOUT reading hidden phase."""
    gci3.check_sealed(report, {"schema","binding","public_digest","plan_digest",
               "source_gci004_report_digest","origin","rounds","scope",
               "coordinator_does_not_read_private_phase","transport_kind"}, SCHEMA)
    require(report["binding"]==binding and
            report["public_digest"]==public["report_digest"] and
            report["plan_digest"]==plan["report_digest"] and
            report["scope"]==SCOPE and
            report["origin"]=="gci005-real-ecpu-mtls-disagreement" and
            report["transport_kind"]=="127.0.0.1-tcp-tlsv1.2+" and
            report["coordinator_does_not_read_private_phase"] is True,
            "source, Ground, scope or private-phase availability claim changed")
    c.gci3.strict_hash(report["source_gci004_report_digest"],"GCI-004 report digest")
    rounds=report.get("rounds")
    require(type(rounds) is list and len(rounds)==2,
            "both agreement and signed-disagreement scenarios required")
    first_values=None
    summary=[]
    for i,round_ in enumerate(rounds):
        require(type(round_) is dict and set(round_)=={
            "scenario","ca_certificate_pem","client_certificate_pem",
            "discovery","receipts","verdict","server_process_count",
            "bad_server_dns_refused","clean_shutdown","phase_withheld",
        }, "unexpected live TLS round fields")
        scenario=SCENARIOS[i]
        require(round_["scenario"]==scenario and
                round_["server_process_count"]==2 and
                round_["bad_server_dns_refused"] is True and
                round_["clean_shutdown"] is True and
                round_["phase_withheld"] is True,
                "test did not establish the declared physical or diagnostic scenario")
        ca=round_["ca_certificate_pem"]
        require(type(ca) is str and "BEGIN CERTIFICATE" in ca,
                "missing test CA identity")
        client=x509.load_pem_x509_certificate(round_["client_certificate_pem"].encode())
        require(client.issuer==x509.load_pem_x509_certificate(ca.encode()).subject,
                "test client cert issuer differs from root")
        discovered=round_["discovery"]
        receipts=round_["receipts"]
        require(type(discovered) is list and len(discovered)==2 and
                type(receipts) is list and len(receipts)==2,
                "expected two authenticated peer identities and signed receipts")
        dns_keys=[]
        values={}
        requests=[]
        seen_challenges=set()
        for idx,peer in enumerate(TWO):
            item,receipt=discovered[idx],receipts[idx]
            require(type(item) is dict and set(item)=={
                "peer_id","dns","feature","certificate_pem","snapshot","snapshot_digest",
                "discovery_rtt_ns","handshake_ns","negotiated_tls",
                "channel_binding_verified"},
                "discovery report fields invalid")
            require(item["peer_id"]==peer and
                    item["dns"]==c.PEERS[peer][1] and item["feature"]==FEATURE,
                    "unexpected peer feature or DNS identity")
            cert=c.check_cert(item["certificate_pem"],ca,item["dns"])
            pub=cert.public_key().public_bytes(
                serialization.Encoding.DER,
                serialization.PublicFormat.SubjectPublicKeyInfo)
            dns_keys.append(pub)
            strict_ns(item["discovery_rtt_ns"],"discovery RTT")
            strict_ns(item["handshake_ns"],"TLS handshake")
            require(item["negotiated_tls"] in ("TLSv1.2","TLSv1.3") and
                    item["channel_binding_verified"] is True,
                    "live TLS peer could not establish authenticated identity")
            c.check_fabric_snapshot(item["snapshot"],peer,FEATURE,item["dns"],binding)
            require(item["snapshot_digest"]==c.jdigest(item["snapshot"]),
                    "E-CPU fabric snapshot digest differs")
            require(type(receipt) is dict and set(receipt)=={
                "peer_id","request","payload","signature_b64","observation_rtt_ns",
                "request_payload_bytes","response_payload_bytes"},
                "receipt report fields invalid")
            require(receipt["peer_id"]==peer,"receipt host identity does not match TLS")
            strict_ns(receipt["observation_rtt_ns"],"observation RTT")
            for k in ("request_payload_bytes","response_payload_bytes"):
                require(type(receipt[k]) is int and 0 < receipt[k] < 1<<20,
                        "MailCPU message size invalid")
            request=receipt["request"]
            require(type(request) is dict and type(request.get("challenge")) is str and
                    re.fullmatch("[0-9a-f]{32}",request["challenge"]) is not None,
                    "invalid challenge nonce")
            expected=c.expected_request(TASK,FEATURE,public,plan,binding,request["challenge"])
            require(request==expected,"observational capability request differs from approved plan")
            seen_challenges.add(request["challenge"])
            payload=receipt["payload"]
            require(type(payload) is dict and type(payload.get("value")) is int and
                    payload["value"] in (0,1),
                    "receipt must provide one strict parity bit")
            require(payload==c.signed_payload(request,peer,item["snapshot_digest"],
                                             payload["value"]),
                    "signed receipt is not bound to exact request and snapshot")
            c.verify_receipt(cert,payload,receipt["signature_b64"])
            values[peer]=payload["value"]
            requests.append(request)
        require(len(set(dns_keys))==2,"two observer peers cannot reuse one signing key")
        require(len(seen_challenges)==1,"paired observations must answer same nonce")
        expected=decisions(values)
        require(round_["verdict"]==expected,
                "signed conflict was incorrectly promoted to an admitted result")
        if i==0:
            require(expected["status"]=="ADMITTED_AGREEMENT",
                    "honest scenario failed to produce agreement")
            first_values=values
        else:
            require(expected["status"]=="REFUSED_DISAGREEMENT" and
                    values["observer-a"]==first_values["observer-a"] and
                    values["observer-b"]!=first_values["observer-b"],
                    "signed false reading did not introduce a distinguishable conflict")
        summary.append({"scenario":scenario,"verdict":expected["status"],
                        "peer_readings":[values[p] for p in TWO],
                        "returned_result":expected["returned_result"]})
    return {"blind_verification":"passed","rounds":summary}


def blind_audit(directory: Path) -> dict[str,Any]:
    binding,public,plan=get_binding(directory)
    report=cag.read(directory/"gci005-quorum.json")
    network=cag.read(directory/"gci004-network.json")
    # Existing network report is already subject to GCI-004's separate
    # source-host attestation; keep its exact digest chained here.
    gci3.check_sealed(network, {"schema","binding","public_digest","plan_digest",
               "origin","ca_certificate_pem","client_certificate_pem","discovery",
               "requests","measurements","realization","scope","transport_kind",
               "bad_hostname_refused","forbidden_feature_refused","replay_refused"}, c.SCHEMA)
    require(network["report_digest"]==report["source_gci004_report_digest"],
            "GCI-005 source network identity is not the attested GCI-004 report")
    summary=verify_record(report,binding,public,plan)
    return c.sealed({"schema":AUDIT_SCHEMA,"status":"authenticated_disagreement_refused_without_phase",
              "ground_fingerprint":binding["ground_fingerprint"],
              "source_digest":binding["source_digest"],
              "public_digest":public["report_digest"],
              "gci004_report_digest":network["report_digest"],
              "gci005_report_digest":report["report_digest"],
              "rounds":summary["rounds"],
              "blind_auditor_received_phase":False,
              "scope":SCOPE})


def witness_audit(directory: Path) -> dict[str,Any]:
    prior=c.verified_report(directory)  # Includes old GCI-003 private witness.
    phase_blind=blind_audit(directory)
    original_blind=cag.read(directory/"gci005-blind-audit.json")
    require(original_blind==phase_blind,
            "privileged witness audit is not bound to the earlier phase-blind report")
    binding,public,_plan=get_binding(directory)
    private=cag.read(directory/"gci003-private.json")
    state=gci3.validate_private(private,public,binding)
    truth=gci3.feature("parity",state)
    for i,round_ in enumerate(phase_blind["rounds"]):
        require(round_["peer_readings"][0]==truth,
                "self-described honest observer does not match private witness")
        if i==0:
            require(round_["peer_readings"][1]==truth,
                    "agreement is not true under independently checked phase witness")
        else:
            require(round_["peer_readings"][1]==1-truth,
                    "signed adversarial witness is not a false source reading")
    return c.sealed({"schema":WITNESS_SCHEMA,
        "status":"signed_false_reading_identified_after_blind_refusal",
        "old_gci004_audit_digest":prior["report_digest"],
        "blind_audit_digest":phase_blind["report_digest"],
        "public_digest":public["report_digest"],
        "phase_commitment":public["phase_commitment"],
        "truth_parity":truth,
        "scope":SCOPE})


def main() -> None:
    parser=argparse.ArgumentParser()
    parser.add_argument("command",choices=("blind","witness"))
    parser.add_argument("--directory",type=Path,required=True)
    args=parser.parse_args()
    try:
        outcome=blind_audit(args.directory) if args.command=="blind" else witness_audit(args.directory)
        name="gci005-blind-audit.json" if args.command=="blind" else "gci005-witness-audit.json"
        cag.persist(args.directory/name,outcome)
        print(outcome["status"],outcome["report_digest"])
    except (ValueError,TypeError,KeyError,AttributeError,OSError) as exc:
        parser.exit(1,f"GCI-005 refused: {type(exc).__name__}: {exc}\n")


if __name__=="__main__":
    main()

"""GCI-004 bounded mTLS observer-fabric receipts and independent verification.

Verification imports neither E-CPU nor VGI. TLS peer transport facts are
runtime-reported; the independent auditor validates the X.509 trust chain,
leaf-key receipt signatures, source context, permitted queries, and the hidden
phase witness separately. The CA is ephemeral and in-run, not external PKI.
"""
from __future__ import annotations

import base64
import datetime
import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any, Mapping

from cryptography import x509
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'gci003'))
import intention_model as gci3

cag = gci3.cag
require = gci3.require
SCHEMA = 'in-formation.gci004-authenticated-observer-fabric/0.1'
AUDIT = 'in-formation.gci004-independent-receipt-audit/0.1'
REQUEST = 'in-formation.gci004-observation-request/0.1'
RECEIPT = 'in-formation.gci004-observation-receipt/0.1'
DNS_CLIENT = 'coordinator.gci004.invalid'
PEERS = {'observer-a': ('parity', 'observer-a.gci004.invalid'),
         'observer-b': ('parity', 'observer-b.gci004.invalid'),
         'observer-c': ('low2', 'observer-c.gci004.invalid')}
OPERATOR = {'parity': 'gci004.observe.parity', 'low2': 'gci004.observe.low2'}
SCOPE = [
    'Distinct OS processes communicate over real loopback TCP mutual TLS on one hosted runner, not independently administered or located machines.',
    'E-CPU mutual-TLS SocketTransport and ComputationalFabricDirectory admit typed peer snapshots on live authenticated sessions.',
    'Leaf X.509 keys sign cryptographically verifiable observation receipts; root CA is ephemeral and generated by the same test job.',
    'Preflight RTT and observation RTT are measured nanoseconds on this runner, not static network cost bounds or external latency forecasts.',
    'Framed application bytes measure serialized MailCPU messages, not TLS ciphertext, Ethernet bytes or energy.',
    'Selection chooses lowest observed discovery RTT among suitable peers, not a guaranteed optimal future request latency.',
    'The receiver phase remains outside the coordinator protocol inputs but is available to receiver processes and final auditor.',
    'A receipt signature authenticates the holder of a test certificate key, not the physical truth of its state measurement.',
    'The final auditor reads the withheld mathematical phase; no external sensor, user secret, or independent federation is claimed.',
]


def jdigest(obj: Any) -> str:
    return cag.digest(obj)


def sealed(data: Mapping[str, Any]) -> dict[str, Any]:
    return gci3.sealed(data)


def payload_bytes(obj: Any) -> int:
    return len(json.dumps(obj, sort_keys=True, separators=(',', ':'), ensure_ascii=False,
                          allow_nan=False).encode('utf-8'))


def require_positive_ns(value: Any, label: str) -> None:
    require(type(value) is int and 0 <= value < 10**12, label + ' is not a measured finite nanosecond count')


def check_cert(cert_pem: str, ca_pem: str, dns: str) -> x509.Certificate:
    """Independently validate in-run test CA and leaf signature, scope, SAN and validity."""
    require(type(cert_pem) is str and type(ca_pem) is str, 'X.509 certificate must be PEM text')
    ca = x509.load_pem_x509_certificate(ca_pem.encode())
    cert = x509.load_pem_x509_certificate(cert_pem.encode())
    require(ca.subject == ca.issuer and cert.issuer == ca.subject, 'issuer mismatch')
    require(ca.extensions.get_extension_for_class(x509.BasicConstraints).value.ca is True,
            'issuer is not a CA')
    require(cert.extensions.get_extension_for_class(x509.BasicConstraints).value.ca is False,
            'peer is not an end-entity certificate')
    require(isinstance(ca.public_key(), ec.EllipticCurvePublicKey), 'unsupported test root')
    ca.public_key().verify(cert.signature, cert.tbs_certificate_bytes,
                           ec.ECDSA(cert.signature_hash_algorithm))
    ca.public_key().verify(ca.signature, ca.tbs_certificate_bytes,
                           ec.ECDSA(ca.signature_hash_algorithm))
    names = cert.extensions.get_extension_for_class(x509.SubjectAlternativeName).value
    require(dns in names.get_values_for_type(x509.DNSName), 'peer SAN identity mismatch')
    require(cert.subject.get_attributes_for_oid(NameOID.COMMON_NAME)[0].value == dns,
            'peer subject differs from authenticated DNS name')
    eku = cert.extensions.get_extension_for_class(x509.ExtendedKeyUsage).value
    require(ExtendedKeyUsageOID.SERVER_AUTH in eku, 'peer certificate lacks server TLS role')
    now = datetime.datetime.now(datetime.timezone.utc)
    require(cert.not_valid_before_utc <= now <= cert.not_valid_after_utc and
            ca.not_valid_before_utc <= now <= ca.not_valid_after_utc,
            'certificate validity period failed')
    return cert


def expected_request(task_id: str, feature: str, public: Mapping[str, Any],
                     plan: Mapping[str, Any], binding: Mapping[str, str],
                     challenge: str) -> dict[str, Any]:
    return {'schema': REQUEST, 'task_id': task_id, 'feature': feature,
            'binding': dict(binding), 'public_digest': public['report_digest'],
            'plan_digest': plan['report_digest'],
            'phase_commitment': public['phase_commitment'], 'challenge': challenge}


def signed_payload(request: Mapping[str, Any], peer_id: str,
                   snapshot_digest: str, value: int) -> dict[str, Any]:
    return {'schema': RECEIPT, 'peer_id': peer_id,
            'snapshot_digest': snapshot_digest,
            'request_digest': jdigest(request),
            'task_id': request['task_id'], 'feature': request['feature'],
            'binding': request['binding'],
            'phase_commitment': request['phase_commitment'],
            'challenge': request['challenge'], 'value': value}


def sign_receipt(private_key: ec.EllipticCurvePrivateKey, payload: Mapping[str, Any]) -> str:
    import json
    signature = private_key.sign(json.dumps(payload, sort_keys=True, separators=(',', ':'),
                                            ensure_ascii=False, allow_nan=False).encode(),
                                 ec.ECDSA(hashes.SHA256()))
    return base64.b64encode(signature).decode('ascii')


def verify_receipt(cert: x509.Certificate, payload: Mapping[str, Any], signature: str) -> None:
    require(type(signature) is str, 'receipt signature type invalid')
    raw = base64.b64decode(signature, validate=True)
    require(isinstance(cert.public_key(), ec.EllipticCurvePublicKey), 'invalid receipt signer type')
    cert.public_key().verify(raw, json.dumps(payload, sort_keys=True, separators=(',', ':'),
                                       ensure_ascii=False, allow_nan=False).encode(),
                             ec.ECDSA(hashes.SHA256()))


def check_fabric_snapshot(snapshot: Mapping[str, Any], peer: str,
                          feature: str, dns: str,
                          binding: Mapping[str, str]) -> None:
    """Independently check exact relevant E-CPU portable snapshot semantics."""
    require(type(snapshot) is dict and set(snapshot) ==
            {'schema', 'endpoint', 'revision', 'lease_seconds', 'hosts', 'links'},
            'unexpected E-CPU snapshot shape')
    ep = snapshot['endpoint']
    require(snapshot['schema'] == 'mailcpu.computational-peer-snapshot.v1' and
            type(snapshot['revision']) is int and snapshot['revision'] >= 1 and
            type(snapshot['lease_seconds']) is int and 1 <= snapshot['lease_seconds'] <= 120 and
            ep['peer_id'] == peer and ep['tls_server_name'] == dns and
            ep['endpoint_host'] == '127.0.0.1' and
            type(ep['port']) is int and 1 <= ep['port'] <= 65535 and
            snapshot['links'] == [] and
            type(snapshot['hosts']) is list and len(snapshot['hosts']) == 1,
            'peer snapshot identity, lifetime, endpoint or host count invalid')
    host = snapshot['hosts'][0]
    spec = host['operator_spec']
    require(host['peer_id'] == peer and host['host_id'] == peer+'-feature' and
            host['computational_ground_fingerprints'] == [binding['ground_fingerprint']] and
            spec['operator_id'] == OPERATOR[feature] and spec['version'] == 1 and
            spec['input_kind'] == 'object' and spec['output_kind'] == 'object' and
            spec['deterministic'] is True and spec['effect_mode'] == 'pure' and
            host['substrates'] == ['cpu'] and
            spec['substrates'] == ['cpu'] and
            host['costs'] == [{'name': 'latency', 'unit': 'ticks', 'amount': 1}],
            'discovered host capability disagrees with binding or executable feature')
    require(type(host['max_bytes']) is int and host['max_bytes'] >= 256,
            'advertised capacity not viable')


def verified_report(directory: Path) -> dict[str, Any]:
    """Verify complete old GCI chain, peer trust, selection, receipts and held phase."""
    old = gci3.audit(directory)
    binding = gci3.certificate_binding(directory)
    public = cag.read(directory / 'gci003-public.json')
    private = cag.read(directory / 'gci003-private.json')
    plan = cag.read(directory / 'gci003-plan.json')
    old_measurements = cag.read(directory / 'gci003-measurements.json')
    state = gci3.validate_private(private, public, binding)
    gci3.validate_plan(plan, public, binding)
    report = cag.read(directory / 'gci004-network.json')
    gci3.check_sealed(report, {'schema', 'binding', 'public_digest', 'plan_digest',
       'origin', 'ca_certificate_pem', 'client_certificate_pem', 'discovery',
       'requests', 'measurements', 'realization', 'scope', 'transport_kind',
       'bad_hostname_refused', 'forbidden_feature_refused', 'replay_refused'}, SCHEMA)
    require(report['origin'] == 'gci004-real-ecpu-mtls-socket-transport' and
            report['transport_kind'] == '127.0.0.1-tcp-tlsv1.2+' and
            report['binding'] == binding and
            report['public_digest'] == public['report_digest'] and
            report['plan_digest'] == plan['report_digest'] and
            report['scope'] == SCOPE and
            report['bad_hostname_refused'] is True and
            report['forbidden_feature_refused'] is True and
            report['replay_refused'] is True,
            'network report provenance, trust or negative handshake conditions invalid')
    client_cert = x509.load_pem_x509_certificate(report['client_certificate_pem'].encode())
    ca_cert = x509.load_pem_x509_certificate(report['ca_certificate_pem'].encode())
    ca_cert.public_key().verify(client_cert.signature, client_cert.tbs_certificate_bytes,
                                ec.ECDSA(client_cert.signature_hash_algorithm))
    require(DNS_CLIENT in client_cert.extensions.get_extension_for_class(
            x509.SubjectAlternativeName).value.get_values_for_type(x509.DNSName),
            'expected mutual-TLS client SAN missing')
    require(len(report['discovery']) == len(PEERS), 'not all observer hosts discovered')
    catalog: dict[str, Any] = {}
    for entry in report['discovery']:
        require(type(entry) is dict and set(entry) == {'peer_id','feature','dns',
           'certificate_pem','snapshot','snapshot_digest','discovery_rtt_ns',
           'handshake_ns','request_payload_bytes','response_payload_bytes',
           'negotiated_tls','channel_binding_verified'},
           'discovery fields differ')
        peer = entry['peer_id']
        require(peer in PEERS and peer not in catalog and
                (entry['feature'],entry['dns']) == PEERS[peer],
                'duplicate, unknown or mismatched peer')
        cert = check_cert(entry['certificate_pem'], report['ca_certificate_pem'],entry['dns'])
        check_fabric_snapshot(entry['snapshot'], peer, entry['feature'], entry['dns'],binding)
        require(entry['snapshot_digest'] == jdigest(entry['snapshot']) and
                entry['negotiated_tls'] in ('TLSv1.2','TLSv1.3') and
                entry['channel_binding_verified'] is True,
                'discovery snapshot digest or TLS binding claim invalid')
        require_positive_ns(entry['discovery_rtt_ns'],'discovery rtt')
        require_positive_ns(entry['handshake_ns'],'handshake')
        require(type(entry['request_payload_bytes']) is int and
                type(entry['response_payload_bytes']) is int and
                entry['request_payload_bytes'] > 0 and entry['response_payload_bytes'] > 0,
                'discovery byte counts invalid')
        catalog[peer] = (entry,cert)
    require(set(catalog) == set(PEERS), 'incomplete authenticated observer catalogue')
    requests = report['requests']
    require(type(requests) is list, 'requests not a list')
    expected_pairs = [(row['case_id'], feat)
                      for row in plan['cases'] for feat in row['selected']]
    require(len(requests) == len(expected_pairs), 'unexpected or missing observer measurement')
    observation_entries=[]
    observed_challenges=set()
    for item,(task_id,feat) in zip(requests,expected_pairs):
        require(type(item) is dict and set(item) == {
            'peer_id','request','payload','signature_b64','observation_rtt_ns',
            'request_payload_bytes','response_payload_bytes'},
            'receipt record shape differs')
        peer=item['peer_id']
        require(peer in catalog and PEERS[peer][0]==feat,
                'receipt peer not a trusted provider of requested feature')
        entry, cert = catalog[peer]
        ranked=sorted((e['discovery_rtt_ns'],e['peer_id'])
              for e,c in catalog.values() if e['feature']==feat)
        require(peer == ranked[0][1], 'selected peer was not minimum measured discovery RTT')
        request=item['request']
        challenge=request.get('challenge')
        require(type(challenge) is str and re.fullmatch('[0-9a-f]{32}',challenge) and
                challenge not in observed_challenges,
                'replayed or malformed request challenge')
        observed_challenges.add(challenge)
        require(request == expected_request(task_id, feat, public, plan, binding, challenge),
                'request not authorized by exact plan, Ground and phase commitment')
        value=gci3.feature(feat, state)
        require(item['payload'] == signed_payload(request, peer,entry['snapshot_digest'],value),
                'signed receipt value or request binding differs from held state')
        verify_receipt(cert,item['payload'],item['signature_b64'])
        require_positive_ns(item['observation_rtt_ns'],'observation rtt')
        require(type(item['request_payload_bytes']) is int and item['request_payload_bytes'] > 0
                and type(item['response_payload_bytes']) is int and item['response_payload_bytes'] > 0,
                'observation byte counts invalid')
        observation_entries.append({'case_id': task_id,
            'readings':[{'name':feat,'value':value}]})
    # Non-measured tasks also have exact empty readings.
    expected_entries=[]
    for row in plan['cases']:
        matching=[entry for entry in observation_entries if entry['case_id']==row['case_id']]
        expected_entries.append({'case_id':row['case_id'],
                                 'readings':[m for entry in matching for m in entry['readings']]})
    require(report['measurements'] == expected_entries,
            'network measurement routing disagrees with observation receipts')
    require(expected_entries == old_measurements['entries'],
            'mTLS observation differs from prior independently controlled E-CPU probe')
    expected_measurement = gci3.sealed({
         'schema':gci3.SCHEMA_MEASUREMENT,'binding':dict(binding),
         'public_digest':public['report_digest'],
         'plan_digest':plan['report_digest'],
         'producer':gci3.PROVIDER,'phase_commitment':public['phase_commitment'],
         'entries':expected_entries,'state_or_phase_disclosed':False})
    expected_result=gci3.resolve(public,plan,expected_measurement,binding)
    require(report['realization'] == expected_result['results'],
            'receipts do not reconstruct the intention-relative result')
    return sealed({'schema':AUDIT,'status':'authenticated-observer-receipts-verified',
        'source_digest':binding['source_digest'],
        'gci003_audit_digest':old['report_digest'],
        'network_report_digest':report['report_digest'],
        'observed_peer_count':len(catalog),
        'signed_observations':len(requests),
        'peer_discovery_rtts_ns':{peer:entry['discovery_rtt_ns'] for peer,(entry,_cert) in catalog.items()},
        'measured_observation_rtts_ns':{x['request']['task_id']:x['observation_rtt_ns'] for x in requests},
        'result_statuses':[x['status'] for x in expected_result['results']],
        'scope':SCOPE})


def main() -> None:
    import argparse
    p=argparse.ArgumentParser()
    p.add_argument('command',choices=('verify',))
    p.add_argument('--directory',type=Path,required=True)
    args=p.parse_args()
    try:
        report=verified_report(args.directory)
        cag.persist(args.directory/'gci004-audit.json',report)
        print(report['status'], report['report_digest'])
    except Exception as e:
        p.exit(1,f'GCI-004 refused: {type(e).__name__}: {e}\n')


if __name__=='__main__':
    main()
